'use strict';
// Shell integration: detects shells and writes their startup files into one folder.
//
//   PowerShell: init.ps1 -> config.ps1 (settings) + profile.ps1 (Linux commands, translation, prompt) + aliases.ps1
//   bash:       init.bash -> profile.bash + aliases.bash      zsh: zsh/.zshrc -> aliases.zsh
//   cmd:        init.cmd (UTF-8 code page, doskey macros)
//
// Aliases (custom commands) are real shell functions, so they work with arguments and pipes.
// When aliases change, `version` changes and open PowerShell/bash/zsh sessions reload before the next prompt.
const fs = require('fs');
const path = require('path');
const { translate } = require('./translate');

const NAME = /^[A-Za-z_][A-Za-z0-9_.-]{0,40}$/;
const RESERVED = new Set(['settings', 'prism', 'cd', 'exit', 'function', 'if', 'for', 'while', 'return']);
const PH = /\{(\d+|args|date|time|user)\}/g;
const validName = n => typeof n === 'string' && NAME.test(n) && !RESERVED.has(n.toLowerCase());

function clean(list) {
  const seen = new Set();
  return (Array.isArray(list) ? list : [])
    .filter(c => c && validName(c.name) && typeof c.body === 'string' && c.body.trim() && !seen.has(c.name.toLowerCase()) && seen.add(c.name.toLowerCase()))
    .map(c => ({ name: c.name, type: c.type === 'text' ? 'text' : 'run', body: c.body.replace(/\r\n?/g, '\n'), desc: String(c.desc || '') }));
}
const hasPH = b => /\{(\d+|args)\}/.test(b);
const single = b => !/[;\n]|&&|\|\|/.test(b.trim());

function listing(cmds) {
  if (!cmds.length) return 'No aliases yet. Add one: prism alias ll \'ls -la\'  (or bash style: alias ll=\'ls -la\')';
  return cmds.map(c => `  ${c.name.padEnd(18)} ${c.desc || (c.type === 'text' ? 'echo: ' : '') + c.body.split('\n')[0]}`).join('\n');
}

// ---------- PowerShell ----------
const psq = s => "'" + String(s).replace(/['\u2018\u2019\u201A\u201B]/g, '$&$&') + "'";
const psText = b => '"' + b.replace(/[`"$\u201C\u201D\u201E]/g, '`$&').replace(PH, (m, k) =>
  k === 'args' ? "$($args -join ' ')" : k === 'date' ? "$(Get-Date -Format 'yyyy-MM-dd')" : k === 'time' ? "$(Get-Date -Format 'HH:mm')"
  : k === 'user' ? '$([Environment]::UserName)' : '$($args[' + (k - 1) + '])') + '"';
const psRun = b => {
  // Bash habits in alias bodies (&&, $VAR, export...) are translated once, here. Bodies run on PowerShell 5.1 and 7.
  let body = b.split('\n').map(l => translate(l, { ps7: false }).line).join('\n');
  body = body.replace(PH, (m, k) => k === 'args' ? '@args' : k === 'date' ? "(Get-Date -Format 'yyyy-MM-dd')" : k === 'time' ? "(Get-Date -Format 'HH:mm')"
    : k === 'user' ? '([Environment]::UserName)' : '$args[' + (k - 1) + ']');
  return !hasPH(b) && single(b) ? body + ' @args' : body;
};

function psAliases(cmds) {
  const L = [
    '# Generated by Prism. Edit aliases in Settings or ~/.config/prism/config.jsonc.',
    'foreach ($n in @($global:__TC_NAMES)) { if ($n) { Remove-Item -Path "function:\\$n" -ErrorAction SilentlyContinue } }',
    '$global:__TC_NAMES = @(' + cmds.map(c => psq(c.name)).join(', ') + ')'
  ];
  for (const c of cmds) {
    L.push(`Remove-Item -Path ${psq('alias:\\' + c.name)} -Force -ErrorAction SilentlyContinue`, `function global:${c.name} {`);
    L.push(c.type === 'text' ? `  Write-Output ${psText(c.body)}` : '  ' + psRun(c.body).replace(/\n/g, '\n  '));
    L.push('}');
  }
  L.push(`function global:__prism_aliases { ${psq(listing(cmds))} -split "\`n" }`);
  return L.join('\r\n') + '\r\n';
}
function psColor(v) { return psq(v || ''); }
function psConfig(cfg) {
  const p = cfg.prompt || {}, col = p.colors || {}, sh = cfg.shell || {};
  const seg = (p.segments || []).map(psq).join(', ');
  return `# Generated by Prism from your settings. Change them in Settings or ~/.config/prism/config.jsonc.
$global:PrismConfig = @{
  translate = $${sh.translate !== false}
  linux = $${sh.linux !== false}
  predictions = $${sh.predictions !== false}
  adminAsk = $${(cfg.admin || {}).ask !== false}
  fetchOnStart = $${!!sh.fetchOnStart}
  prompt = @{
    style = ${psq(p.style || 'auto')}
    segments = @(${seg})
    symbol = ${psq(p.symbol || '❯')}
    newline = $${p.newline !== false}
    blankLine = $${!!p.blankLine}
    unixPaths = $${p.unixPaths !== false}
    pathDepth = ${Number.isFinite(+p.pathDepth) ? +p.pathDepth : 3}
    gitSymbol = ${psq(p.gitSymbol ?? ' ')}
    durationMin = ${Number.isFinite(+p.durationMin) ? +p.durationMin : 2}
    colors = @{ path = ${psColor(col.path)}; git = ${psColor(col.git)}; symbol = ${psColor(col.symbol)}; error = ${psColor(col.error)}; muted = ${psColor(col.muted)}; user = ${psColor(col.user)}; host = ${psColor(col.host)} }
  }
}
`.replace(/\n/g, '\r\n');
}
function psInit(dir) {
  return `# Prism: PowerShell startup
$global:__TC_DIR = ${psq(dir)}
$global:__TC_VER = ''
function global:__tc_reload {
  try { $v = [IO.File]::ReadAllText((Join-Path $global:__TC_DIR 'version')).Trim() } catch { return }
  if ($v -ne $global:__TC_VER) {
    $global:__TC_VER = $v
    . (Join-Path $global:__TC_DIR 'config.ps1')
    . (Join-Path $global:__TC_DIR 'aliases.ps1')
  }
}
. (Join-Path $global:__TC_DIR 'config.ps1')
. (Join-Path $global:__TC_DIR 'profile.ps1')
__tc_reload
`.replace(/\n/g, '\r\n');
}

// ---------- bash / zsh ----------
const sq = s => "'" + String(s).replace(/'/g, "'\\''") + "'";
const shText = b => '"' + b.replace(/[\\"`$]/g, '\\$&').replace(PH, (m, k) =>
  k === 'args' ? '$*' : k === 'date' ? '$(date +%Y-%m-%d)' : k === 'time' ? '$(date +%H:%M)' : k === 'user' ? '$USER' : '${' + k + '}') + '"';
const shRun = b => {
  const body = b.replace(PH, (m, k) => k === 'args' ? '"$@"' : k === 'date' ? '"$(date +%Y-%m-%d)"' : k === 'time' ? '"$(date +%H:%M)"' : k === 'user' ? '"$USER"' : '"${' + k + '}"');
  return !hasPH(b) && single(b) ? body + ' "$@"' : body;
};
function shAliases(cmds, zsh) {
  const L = [
    '# Generated by Prism.',
    zsh ? 'for __n in ${=__TC_NAMES}; do unfunction "$__n" 2>/dev/null; done' : 'for __n in $__TC_NAMES; do unset -f "$__n" 2>/dev/null; done',
    '__TC_NAMES=' + sq(cmds.map(c => c.name).join(' '))
  ];
  for (const c of cmds) {
    L.push(`unalias ${c.name} 2>/dev/null`, `function ${c.name} {`);
    L.push(c.type === 'text' ? `  printf '%s\\n' ${shText(c.body)}` : '  ' + shRun(c.body).trim());
    L.push('}');
  }
  L.push(`__prism_aliases() { printf '%s\\n' ${sq(listing(cmds))}; }`);
  return L.join('\n') + '\n';
}
const hexEsc = h => /^#[0-9a-f]{6}$/i.test(h || '') ? `\\[\\e[38;2;${parseInt(h.slice(1, 3), 16)};${parseInt(h.slice(3, 5), 16)};${parseInt(h.slice(5, 7), 16)}m\\]` : '';
function bashInit(dir, cfg) {
  const p = cfg.prompt || {}, col = p.colors || {};
  const keep = p.style === 'keep';
  return `# Prism: bash startup
if [ -f ~/.bashrc ]; then . ~/.bashrc; elif [ -f ~/.bash_profile ]; then . ~/.bash_profile; fi
__TC_DIR=${sq(dir)}
__TC_VER=
PRISM_SYMBOL=${sq(p.symbol || '❯')}
PRISM_C_PATH=${sq(hexEsc(col.path))}; PRISM_C_GIT=${sq(hexEsc(col.git))}; PRISM_C_SYM=${sq(hexEsc(col.symbol))}; PRISM_C_ERR=${sq(hexEsc(col.error))}
PRISM_KEEP_PROMPT=${keep ? 1 : 0}
. "$__TC_DIR/profile.bash"
__tc_reload() {
  local v; read -r v < "$__TC_DIR/version" 2>/dev/null
  if [ "$v" != "$__TC_VER" ]; then __TC_VER=$v; . "$__TC_DIR/aliases.bash"; fi
}
__tc_reload
PROMPT_COMMAND="__prism_prompt\${PROMPT_COMMAND:+;$PROMPT_COMMAND}"
`;
}
function zshFiles(dir) {
  const real = 'REAL="${TC_REAL_ZDOTDIR:-$HOME}"';
  return {
    '.zshenv': `${real}; [ -f "$REAL/.zshenv" ] && source "$REAL/.zshenv"\n`,
    '.zprofile': `${real}; [ -f "$REAL/.zprofile" ] && source "$REAL/.zprofile"\n`,
    '.zshrc': `# Prism: zsh startup
ZDOTDIR="\${TC_REAL_ZDOTDIR:-$HOME}"
[ -f "$ZDOTDIR/.zshrc" ] && source "$ZDOTDIR/.zshrc"
__TC_DIR=${sq(dir)}
__TC_VER=
__prism_msg() { if [ -n "$PRISM_INBOX" ] && [ -d "$PRISM_INBOX" ]; then printf '%s\\n' "$1" > "$PRISM_INBOX/sh-$$-$RANDOM$RANDOM.msg"; else printf '\\033]7777;%s\\007' "$1"; fi; }
settings() { __prism_msg "panel;$*"; }
__tc_reload() { local v; v=$(<"$__TC_DIR/version") 2>/dev/null; if [[ "$v" != "$__TC_VER" ]]; then __TC_VER=$v; source "$__TC_DIR/aliases.zsh"; fi; }
__tc_reload
autoload -Uz add-zsh-hook && add-zsh-hook precmd __tc_reload
`
  };
}

// ---------- cmd ----------
// init.cmd switches the console to UTF-8 first, so the macros (and any non-ASCII text) are read correctly.
// Each macro is one line joined with & (doskey's $T would print the prompt between parts).
const cmdSpecial = /[\^&|<>"]/g;
const doskeyDollar = t => t.replace(/\$/g, '$$$$');
const cmdPH = t => t.replace(PH, (m, k) =>
  k === 'args' ? '$*' : k === 'date' ? '%DATE%' : k === 'time' ? '%TIME:~0,5%' : k === 'user' ? '%USERNAME%' : (+k <= 9 ? '$' + k : ''));
const echoLines = text => '@' + text.split('\n').map(l => 'echo(' + cmdPH(doskeyDollar(l).replace(cmdSpecial, '^$&'))).join('& ');
const runLine = body => '@' + body.split(/\s*(?:;|\n|&&)\s*/).filter(Boolean).map(x => cmdPH(doskeyDollar(x))).join(' & ') + (!hasPH(body) && single(body) ? ' $*' : '');
const batchDef = (name, macro) => `@doskey ${name}=` + macro.replace(/%/g, '%%').replace(cmdSpecial, '^$&');
function cmdInit(cmds, dir) {
  const msg = m => `@echo(${m}>"%PRISM_INBOX%\\cmd-%RANDOM%%RANDOM%.msg"`;
  const defs = [
    ...cmds.map(c => [c.name, c.type === 'text' ? echoLines(c.body) : runLine(c.body)]),
    ['settings', msg('panel;$*')],
    // the command goes through an environment variable so its quotes and & survive
    ['sudo', `set "PRISM_SUDO=$*" & powershell.exe -NoLogo -NoProfile -ExecutionPolicy Bypass -File "${path.join(dir, 'elevate.ps1')}" -Kind cmd`],
    ...['fetch', 'lava', 'matrix', 'pipes', 'donut', 'clock', 'visualizer', 'cava', 'toys'].map(t => [t, `powershell.exe -NoLogo -NoProfile -ExecutionPolicy Bypass -File "${path.join(dir, 'elevate.ps1')}" -Toy ${t} $*`]),
    ['aliases', echoLines(listing(cmds))]
  ];
  return ['@chcp 65001 >nul', '@prompt $E[1;34m$P$E[0m$_$E[32m$G$E[0m ', ...defs.map(([n, m]) => batchDef(n, m))].join('\r\n') + '\r\n';
}

// ---------- write everything ----------
function writeAll(dir, cfg, staticDir, platform = process.platform) {
  const cmds = clean(cfg.aliases);
  const shDir = platform === 'win32' ? dir.replace(/\\/g, '/') : dir;
  fs.mkdirSync(path.join(dir, 'zsh'), { recursive: true });
  const BOM = '\uFEFF';
  const read = f => fs.readFileSync(path.join(staticDir, f), 'utf8').replace(/^\uFEFF/, '');
  const files = {
    'profile.ps1': BOM + read('profile.ps1'),
    'profile.bash': read('profile.bash'),
    'config.ps1': BOM + psConfig(cfg),
    'aliases.ps1': BOM + psAliases(cmds),
    'init.ps1': BOM + psInit(dir),
    'aliases.bash': shAliases(cmds, false),
    'aliases.zsh': shAliases(cmds, true),
    'init.bash': bashInit(shDir, cfg),
    'init.cmd': cmdInit(cmds, dir),
    'elevate.ps1': BOM + read('elevate.ps1')
  };
  for (const [f, s] of Object.entries(files)) fs.writeFileSync(path.join(dir, f), s);
  for (const [f, s] of Object.entries(zshFiles(shDir))) fs.writeFileSync(path.join(dir, 'zsh', f), s);
  fs.writeFileSync(path.join(dir, 'version'), String(Date.now()) + '\n'); // last: tells open sessions to reload
  return cmds;
}

// ---------- shells on this machine ----------
const exists = p => { try { return fs.statSync(p).isFile(); } catch { return false; } };
function which(cmd, platform) {
  const exts = platform === 'win32' ? ['.exe', '.cmd', ''] : [''];
  for (const d of (process.env.PATH || '').split(path.delimiter)) for (const e of exts) {
    const p = path.join(d, cmd + e);
    if (exists(p)) return p;
  }
  return null;
}
function kindOf(file) {
  const b = path.basename(file).toLowerCase().replace(/\.exe$/, '');
  return { bash: 'bash', zsh: 'zsh', pwsh: 'pwsh', powershell: 'pwsh', cmd: 'cmd' }[b] || 'other';
}
function detectProfiles(platform = process.platform) {
  const list = [];
  if (platform === 'win32') {
    const pw = which('pwsh', platform);
    list.push({ id: 'prism', name: 'Prism', cmd: pw || 'powershell.exe', kind: 'pwsh', prism: true });
    if (pw) list.push({ id: 'pwsh', name: 'PowerShell 7', cmd: pw, kind: 'pwsh' });
    list.push({ id: 'powershell', name: 'Windows PowerShell', cmd: 'powershell.exe', kind: 'pwsh' });
    list.push({ id: 'cmd', name: 'Command Prompt', cmd: process.env.ComSpec || 'cmd.exe', kind: 'cmd' });
    const gb = ['C:\\Program Files\\Git\\bin\\bash.exe', 'C:\\Program Files (x86)\\Git\\bin\\bash.exe'].find(exists);
    if (gb) list.push({ id: 'gitbash', name: 'Git Bash', cmd: gb, kind: 'bash' });
    if (which('wsl', platform)) list.push({ id: 'wsl', name: 'WSL', cmd: 'wsl.exe', kind: 'other' });
  } else {
    let shells = [];
    try { shells = fs.readFileSync('/etc/shells', 'utf8').split('\n').map(s => s.trim()).filter(s => s.startsWith('/') && exists(s)); } catch {}
    if (process.env.SHELL) shells.unshift(process.env.SHELL);
    const seen = new Set();
    for (const s of shells) {
      const b = path.basename(s);
      if (seen.has(b) || ['sh', 'dash', 'rbash', 'nologin', 'false'].includes(b)) continue;
      seen.add(b);
      list.push({ id: b, name: b, cmd: s, kind: kindOf(s) });
    }
    if (!list.length) list.push({ id: 'sh', name: 'sh', cmd: '/bin/sh', kind: 'other' });
  }
  return list;
}

module.exports = { writeAll, detectProfiles, clean, validName, listing, _gen: { psAliases, psConfig, shAliases, cmdInit, psRun } };
